import assert from 'node:assert/strict';
import {FIRST_GUIDE_KEY,prepareFirstGuide,readFirstGuide,advanceFirstGuide,renderFirstRoomGuide} from '../js/first-area-guide.js';
import {FAILURE_NOTICE_KEY,FAILURE_NOTICE_MS,beginFailureNotice,failureNoticeRemaining,renderFailureNotice} from '../js/ending-notice.js';
import {resetCurrentGame} from '../js/teacher-mode-data.js';
import {createPlayStorage} from '../js/play-mode.js';
import {renderYearOrder} from '../js/year-order-ui.js';
import {newYearOrder,placeYearCard} from '../js/year-order-data.js';
const records=new Map(),base={getItem:key=>records.get(key)||null,setItem:(key,value)=>records.set(key,value),removeItem:key=>records.delete(key)};
const normal=createPlayStorage(base),test=createPlayStorage(base,true);
const rooms=Array.from({length:8},()=>({state:{started:false,solved:[]}}));
assert.equal(prepareFirstGuide(normal,rooms).step,'area');
advanceFirstGuide(normal,7,'start');
assert.ok(renderFirstRoomGuide(normal,7,'welcome').includes('ナゾに挑む'));
assert.equal(renderFirstRoomGuide(normal,1,'welcome'),'','The guide follows the selected area instead of forcing an area');
advanceFirstGuide(normal,7,'question');assert.ok(renderFirstRoomGuide(normal,7,'room').includes('①のナゾ'));
advanceFirstGuide(normal,7,'done');
assert.equal(renderFirstRoomGuide(normal,7,'room'),'');
assert.equal(prepareFirstGuide(normal,rooms).step,'done','Returning to the hub never restarts the first guide');
assert.equal(prepareFirstGuide(test,rooms).step,'area','Test and normal guides are separate');
resetCurrentGame(normal,{removeItem(){}});assert.equal(readFirstGuide(normal),null);assert.equal(readFirstGuide(test).step,'area');
rooms[4].state.started=true;assert.equal(prepareFirstGuide(normal,rooms).step,'done','Existing games do not get a new tutorial');
const failed={submitted:true,result:'rescued',decidedAt:1000,revealAt:2000};
assert.equal(beginFailureNotice(normal,failed,2500),2500);
assert.equal(failureNoticeRemaining(2500,7499),1);
assert.equal(failureNoticeRemaining(2500,7500),0,'The failure notice lasts five seconds');
assert.equal(beginFailureNotice(normal,failed,4500),2500,'Reloads preserve the notice start');
assert.equal(beginFailureNotice(normal,failed,9000),2500,'Finished notices do not repeat');
assert.equal(beginFailureNotice(normal,{...failed,decidedAt:3000},9000),9000,'New games get their own notice');
assert.equal(beginFailureNotice(normal,{...failed,result:'success'},10000),null);
assert.equal(beginFailureNotice(normal,{...failed,submitted:false},10000),null);
assert.equal(failureNoticeRemaining(null,10000),0);
assert.match(renderFailureNotice(),/<h1>残念！<\/h1>/);
assert.ok(!renderFailureNotice().includes('脱出できません'));
resetCurrentGame(normal,{removeItem(){}});assert.equal(normal.getItem(FAILURE_NOTICE_KEY),null);assert.equal(normal.getItem(FIRST_GUIDE_KEY),null);
const order=newYearOrder();assert.ok(renderYearOrder(order).includes('まず、いちばん早く起きたできごとをクリック！'));
placeYearCard(order,1);assert.ok(renderYearOrder(order).includes('次に起きたできごとをクリック！'));
for(const n of [4,6,7,8])placeYearCard(order,n);assert.ok(renderYearOrder(order).includes('5つのできごとを選びました'));
assert.equal(FAILURE_NOTICE_MS,5000);
console.log('PASS: first-area guidance lifecycle and existing-game migration, test isolation, reset, chronological click prompts, five-second failure notice, reloads and success bypass');
